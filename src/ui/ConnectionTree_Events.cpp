void ConnectionTree::NewObject(ConnEntry* e, const wxString& db, ObjectKind kind)
{
    if (!e || !e->IsConnected() || !hooks_.newObjectEditor) return;
    active_ = e; e->currentDb = db;
    const db::Dialect d = e->conn->GetDialect();
    hooks_.newObjectEditor(e, db, ObjectNewTitle(kind), ObjectTemplate(kind, d), kind);
}

void ConnectionTree::ModifyObject(ConnEntry* e, const wxString& db,
                                  const wxString& name, ObjectKind kind)
{
    if (!e || !e->IsConnected() || name.IsEmpty() || !hooks_.newObjectEditor) return;
    active_ = e; e->currentDb = db;
    db::IConnection* c = e->conn.get();
    const db::Dialect d = c->GetDialect();

    // Fetch the object's current definition (synchronous, like 复制 CREATE 语句).
    wxString ddl, err;
    bool ok = false;
    if (kind == ObjectKind::View) {
        ok = c->GetViewDdl(db, name, ddl, err);
    } else {   // Function / Procedure
        db::RoutineInfo r;
        r.name = name;
        r.type = (kind == ObjectKind::Procedure) ? L"PROCEDURE" : L"FUNCTION";
        ok = c->GetRoutineDdl(db, r, ddl, err);
    }
    if (!ok) {
        wxMessageBox(tr(L"读取对象定义失败:") + L"\n\n" + err, tr(L"修改"),
                     wxOK | wxICON_ERROR, dialogParent_);
        return;
    }
    hooks_.newObjectEditor(e, db, name, ObjectModifyDdl(kind, d, name, ddl), kind);
}

// Prompt for parameters, then run the routine in a fresh query tab so its result
// (a procedure's OUT/result set, or a function's returned value) lands in the
// shared results grid — no bespoke result surface.
void ConnectionTree::ExecuteRoutine(ConnEntry* e, const wxString& db,
                                    const wxString& name, bool isProcedure)
{
    if (!e || !e->IsConnected() || name.IsEmpty() || !hooks_.newQueryRun) return;
    active_ = e; e->currentDb = db;
    const db::Dialect d = e->conn->GetDialect();

    RoutineExecDialog dlg(dialogParent_, name, isProcedure, d);
    if (dlg.ShowModal() != wxID_OK) return;
    const wxString sql = dlg.CallStatement();
    if (sql.IsEmpty()) return;
    hooks_.newQueryRun(e, db, sql);
}

// Oracle/DM only: ALTER {FUNCTION|PROCEDURE|PACKAGE} <name> COMPILE. On failure a
// resizable error window shows the full diagnostics with a 复制 button. Callers
// gate this menu item off for engines without a COMPILE concept (MySQL/PG).
void ConnectionTree::CompileObject(ConnEntry* e, const wxString& db,
                                   const wxString& name, ObjectKind kind)
{
    if (!e || !e->IsConnected() || name.IsEmpty()) return;
    active_ = e; e->currentDb = db;
    db::IConnection* c = e->conn.get();

    wxString type;
    switch (kind) {
    case ObjectKind::Function:  type = L"FUNCTION";  break;
    case ObjectKind::Procedure: type = L"PROCEDURE"; break;
    case ObjectKind::Package:   type = L"PACKAGE";   break;
    default: return;
    }
    const wxString sql = L"ALTER " + type + L" " +
                         db::QuoteIdent(name, c->GetDialect()) + L" COMPILE";

    db::QueryResult r;
    wxString err;
    if (c->Execute(sql, r, err)) {
        if (hooks_.status) hooks_.status(wxString::Format(tr(L"%s 编译成功"), name));
        wxMessageBox(wxString::Format(tr(L"%s 编译成功"), name), tr(L"编译"),
                     wxOK | wxICON_INFORMATION, dialogParent_);
    } else {
        ShowSqlError(dialogParent_, tr(L"编译错误"), err);
    }
}

// Refresh the 表 folder in the tree (Category is internal, so this thin wrapper lets
