// A solid-colour square for a "设置颜色" menu item's bitmap.
wxBitmap ColorSwatch(const wxColour& c, int size = 14)
{
    wxBitmap bm(size, size);
    wxMemoryDC dc(bm);
    dc.SetBackground(wxBrush(c));
    dc.Clear();
    dc.SetPen(wxPen(wxColour(0, 0, 0, 40)));   // faint outline so light swatches read
    dc.SetBrush(*wxTRANSPARENT_BRUSH);
    dc.DrawRectangle(0, 0, size, size);
    dc.SelectObject(wxNullBitmap);
    return bm;
}

