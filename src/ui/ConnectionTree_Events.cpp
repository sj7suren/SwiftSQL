// Incremental sidebar search (SearchJump) — see ConnectionTree.h for behavior and
// the lazy-load caveat.

// Depth-first flatten of every NodeData-tagged node under `parent`, in the tree's
// natural (visible) order. The "加载中…" lazy-load placeholders are appended without
// a wxTreeItemData, so gating on a non-null GetItemData skips them. `parent` itself
// is never added (callers pass the hidden root_).
void ConnectionTree::CollectSearchNodes(const wxTreeItemId& parent,
                                        std::vector<wxTreeItemId>& out) const
{
    if (!parent.IsOk()) return;
    wxTreeItemIdValue cookie;
    for (wxTreeItemId child = tree_->GetFirstChild(parent, cookie); child.IsOk();
         child = tree_->GetNextChild(parent, cookie)) {
        if (tree_->GetItemData(child))   // real node (placeholders carry none)
            out.push_back(child);
        CollectSearchNodes(child, out);  // recurse into already-loaded descendants
    }
}

// Un-bold the node highlighted by the previous SearchJump, if it is still a live node.
void ConnectionTree::ClearSearchHighlight()
{
    if (searchBold_.IsOk() && tree_->GetItemData(searchBold_))
        tree_->SetItemBold(searchBold_, false);
    searchBold_ = wxTreeItemId{};
}

bool ConnectionTree::SearchJump(const wxString& query, bool next)
{
    if (!tree_ || !root_.IsOk()) return false;
    ClearSearchHighlight();   // drop the previous round's bold highlight

    wxString q = query.Lower();
    q.Trim(true).Trim(false);
    if (q.IsEmpty()) return true;   // cleared box → highlight dropped, tree left as-is

    std::vector<wxTreeItemId> nodes;
    CollectSearchNodes(root_, nodes);

    // Case-insensitive substring match on the node label; record positions so "next"
    // can advance relative to the current selection.
    std::vector<size_t> matches;
    for (size_t i = 0; i < nodes.size(); ++i)
        if (tree_->GetItemText(nodes[i]).Lower().Contains(q))
            matches.push_back(i);

    if (matches.empty()) {
        if (hooks_.status) hooks_.status(tr(L"无匹配"));
        return false;
    }

    // Target: the first match by default; for "next", the first match strictly after
    // the current selection, wrapping back to matches.front() when past the last one.
    size_t targetIdx = matches.front();
    if (next) {
        wxTreeItemId sel = tree_->GetSelection();
        int selPos = -1;
        if (sel.IsOk())
            for (size_t i = 0; i < nodes.size(); ++i)
                if (nodes[i] == sel) { selPos = static_cast<int>(i); break; }
        for (size_t m : matches)
            if (static_cast<int>(m) > selPos) { targetIdx = m; break; }
    }

    wxTreeItemId target = nodes[targetIdx];
    if (!target.IsOk()) return false;
    tree_->EnsureVisible(target);   // expands ancestors so the match is on-screen
    tree_->SelectItem(target);
    tree_->ScrollTo(target);
    tree_->SetItemBold(target, true);
    searchBold_ = target;
    return true;
}

