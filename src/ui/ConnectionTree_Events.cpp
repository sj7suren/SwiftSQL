// Map an object kind to the tree folder its instances live in, then reload that
// folder. Package has no dedicated category folder in the sidebar, so it's a no-op.
void ConnectionTree::RefreshCategory(ConnEntry* e, const wxString& db, ObjectKind kind)
{
    switch (kind) {
    case ObjectKind::View:      RefreshCategory(e, db, Category::Views);      break;
    case ObjectKind::Function:  RefreshCategory(e, db, Category::Functions);  break;
    case ObjectKind::Procedure: RefreshCategory(e, db, Category::Procedures); break;
    case ObjectKind::Package:   break;   // no Packages folder in the tree
    }
}

// Reload the (db, cat) folder in the tree so a just-created / renamed object shows
// up. Located by walking the connection node's children for the database, then that
// database's children for the category folder. Silent no-op when the entry is dead,
// the database isn't opened (categories not built), or the folder was never expanded
// (still shows its 加载中… placeholder — a fresh lazy-load will include the new
// object). Must run on the GUI thread (it mutates tree nodes + kicks the loader).
void ConnectionTree::RefreshCategory(ConnEntry* e, const wxString& db, Category cat)
{
    // The walk itself is FindCategoryNode (ConnectionTree_Groups.cpp), shared
    // with the 分组 code which needs to locate the same folder to repaint it.
    // Two copies of "find the (db, cat) node" is how the two would drift into
    // disagreeing about which folder they are talking about.
    const wxTreeItemId catNode = FindCategoryNode(e, db, cat);
    if (!catNode.IsOk()) return;
    auto* cd = dynamic_cast<NodeData*>(tree_->GetItemData(catNode));
    if (!cd || !cd->loaded) return;   // folder never expanded → lazy-load will show it later
    cd->loaded = false;
    LoadCategoryMembers(catNode);     // async reload; keep it expanded as it already was
    tree_->Expand(catNode);
}

