// A starter CREATE TABLE statement for the dialect — "新建表" opens a query
// prefilled with this so the user edits a real, idiomatic skeleton (auto-inc /
// identity / serial differ per engine) instead of a blank page.
inline wxString NewTableTemplate(db::Dialect d)
{
    switch (d) {
    case db::Dialect::Postgres:
        return L"CREATE TABLE new_table (\n"
               L"    id          SERIAL PRIMARY KEY,\n"
               L"    name        VARCHAR(255) NOT NULL,\n"
               L"    created_at  TIMESTAMP DEFAULT CURRENT_TIMESTAMP\n"
               L");\n";
    case db::Dialect::Sqlite:
        return L"CREATE TABLE new_table (\n"
               L"    id          INTEGER PRIMARY KEY AUTOINCREMENT,\n"
               L"    name        TEXT NOT NULL,\n"
               L"    created_at  TEXT DEFAULT (datetime('now'))\n"
               L");\n";
    case db::Dialect::SqlServer:
        return L"CREATE TABLE new_table (\n"
               L"    id          INT IDENTITY(1,1) PRIMARY KEY,\n"
               L"    name        NVARCHAR(255) NOT NULL,\n"
               L"    created_at  DATETIME DEFAULT GETDATE()\n"
               L");\n";
    case db::Dialect::Oracle:
        // 12c+ IDENTITY column; VARCHAR2 is Oracle's canonical string type. DM8
        // accepts this verbatim (Oracle-compatible DDL).
        return L"CREATE TABLE new_table (\n"
               L"    id          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,\n"
               L"    name        VARCHAR2(255) NOT NULL,\n"
               L"    created_at  TIMESTAMP DEFAULT CURRENT_TIMESTAMP\n"
               L");\n";
    case db::Dialect::MySQL:
    default:
        return L"CREATE TABLE new_table (\n"
               L"    id          INT AUTO_INCREMENT PRIMARY KEY,\n"
               L"    name        VARCHAR(255) NOT NULL,\n"
               L"    created_at  TIMESTAMP DEFAULT CURRENT_TIMESTAMP\n"
               L") ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;\n";
    }
}

